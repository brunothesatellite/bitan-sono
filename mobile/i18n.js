export function createTranslator(initial = "fr") {
  let lang = I18N[initial] ? initial : "fr";
  const t = (key, vars) => {
    let text = (I18N[lang] && I18N[lang][key]) ?? I18N.fr[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
    }
    return text;
  };
  return {
    t,
    setLang(next) {
      if (I18N[next]) lang = next;
      return lang;
    },
    get lang() {
      return lang;
    },
  };
}
